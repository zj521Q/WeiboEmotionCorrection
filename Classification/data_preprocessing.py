os.makedirs(merged_dir, exist_ok=True)
os.makedirs(preproc_output_dir, exist_ok=True)

major_data = {major: [] for major in major_categories}

for subfolder in os.listdir(input_dir):
    subfolder_path = os.path.join(input_dir, subfolder)
    if not os.path.isdir(subfolder_path):
        continue
    for major, sublist in major_categories.items():
        if subfolder in sublist:
            path = os.path.join(subfolder_path, f"{subfolder}.csv")
            if not os.path.exists(path):
                break
            try:
                df = pd.read_csv(path, encoding="utf-8")
            except UnicodeDecodeError:
                df = pd.read_csv(path, encoding="gbk")
            if "微博正文" not in df.columns:
                break
            texts = df["微博正文"].dropna().astype(str).tolist()
            major_data[major].extend(texts)
            break

for major, texts in major_data.items():
    unique_texts = list(dict.fromkeys(texts))
    out_df = pd.DataFrame({'微博正文': unique_texts})
    out_df.to_csv(os.path.join(merged_dir, f"{major}.csv"), index=False, encoding="utf-8-sig")
    print(f"[合并去重] {major}: {len(unique_texts)} 条")

for fname in os.listdir(merged_dir):
    if not fname.endswith('.csv'):
        continue
    cat = fname.replace('.csv', '')
    df = pd.read_csv(os.path.join(merged_dir, fname), encoding="utf-8")
    df["处理后文本"] = df["微博正文"].astype(str).apply(clean_text)
    df = df[df["处理后文本"].str.strip() != ""].reset_index(drop=True)
    cleaned_n = len(df)
    if cleaned_n > MAX_PER_CAT:
        df = df.sample(n=MAX_PER_CAT, random_state=RANDOM_SEED).reset_index(drop=True)
    sampled_n = len(df)
    out_path = os.path.join(preproc_output_dir, fname)
    df[['处理后文本']].to_csv(out_path, index=False, encoding="utf-8-sig")
    print(f"[{cat}] 清洗后 {cleaned_n} 条，最终 {sampled_n} 条")